create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.games (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  slug text not null unique,
  thumbnail text,
  description text not null default '',
  developer text,
  release_date date,
  file_size text,
  min_req_win text,
  min_req_android text,
  is_featured boolean not null default false,
  is_18_plus boolean not null default true,
  download_count integer not null default 0 check (download_count >= 0),
  views_count integer not null default 0 check (views_count >= 0),
  category_id bigint references public.categories(id) on delete set null,
  user_id text,
  created_at timestamptz not null default now()
);

create table if not exists public.game_galleries (
  id uuid primary key default gen_random_uuid(),
  game_id uuid not null references public.games(id) on delete cascade,
  image_url text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.download_links (
  id uuid primary key default gen_random_uuid(),
  game_id uuid not null references public.games(id) on delete cascade,
  platform text not null check (platform in ('windows', 'android')),
  server_name text not null,
  destination_url text not null,
  created_at timestamptz not null default now(),
  unique (game_id, platform, server_name)
);

create table if not exists public.comments (
  id uuid primary key default gen_random_uuid(),
  game_id uuid not null references public.games(id) on delete cascade,
  author_name text not null check (char_length(author_name) between 1 and 80),
  comment_text text not null check (char_length(comment_text) between 1 and 3000),
  created_at timestamptz not null default now()
);

create index if not exists games_created_at_idx on public.games (created_at desc);
create index if not exists games_category_id_idx on public.games (category_id);
create index if not exists games_featured_idx on public.games (is_featured) where is_featured;
create index if not exists game_galleries_game_id_idx on public.game_galleries (game_id);
create index if not exists download_links_game_platform_idx on public.download_links (game_id, platform);
create index if not exists comments_game_created_idx on public.comments (game_id, created_at desc);

alter table public.categories enable row level security;
alter table public.games enable row level security;
alter table public.game_galleries enable row level security;
alter table public.download_links enable row level security;
alter table public.comments enable row level security;

drop policy if exists "Public can read categories" on public.categories;
create policy "Public can read categories" on public.categories
  for select to anon, authenticated using (true);

drop policy if exists "Public can read games" on public.games;
create policy "Public can read games" on public.games
  for select to anon, authenticated using (true);

drop policy if exists "Public can read game galleries" on public.game_galleries;
create policy "Public can read game galleries" on public.game_galleries
  for select to anon, authenticated using (true);

drop policy if exists "Public can read download links" on public.download_links;
create policy "Public can read download links" on public.download_links
  for select to anon, authenticated using (true);

drop policy if exists "Public can read comments" on public.comments;
create policy "Public can read comments" on public.comments
  for select to anon, authenticated using (true);

drop policy if exists "Visitors can submit comments" on public.comments;
create policy "Visitors can submit comments" on public.comments
  for insert to anon, authenticated
  with check (
    char_length(author_name) between 1 and 80
    and char_length(comment_text) between 1 and 3000
  );

grant select on public.categories, public.games, public.game_galleries,
  public.download_links, public.comments to anon, authenticated;
grant insert on public.comments to anon, authenticated;

